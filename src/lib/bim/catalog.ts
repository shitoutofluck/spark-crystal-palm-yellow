export function finishOf(id: string): Finish {
  return CATALOG[id] ?? CATALOG["timber-spf"]!;
}

export function facadeMatId(facade: "stucco" | "brick" | "panel" | "siding"): string {
  if (facade === "brick") return "brick-red";
  if (facade === "panel") return "panel-fiber";
  if (facade === "siding") return "vinyl-gray";
  return "stucco-warm";
}

export function roofMatId(roof: "flat" | "shed" | "gable"): string {
  return roof === "gable" ? "shingle-charcoal" : "membrane-charcoal";
}

export function tintedFinish(base: Finish, hex: string): Finish {
  return {
    ...base,
    id: `${base.id}#${hex.replace("#", "")}`,
    hex,
    name: `${base.name} · ${hex}`,
  };
}
